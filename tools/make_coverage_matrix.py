#!/usr/bin/env python3
"""Generate docs/coverage-matrix.md: every exam-guide v1.1 skill -> guide files mentioning it, practice questions tagged with it.
Skill list is parsed from docs/notes/exam-guide.md. Run from repo root after build_practice.py."""
import re, glob, collections, sys, os
sys.path.insert(0, "practice")
from build_practice import parse

BS = chr(92)
notes = open("docs/notes/exam-guide.md", encoding="utf-8").read()
# skills appear as 'N.N.N text' inside the task bullet lines; also capture task statement ids N.N
skill_ids = sorted(set(re.findall(r"\b([1-4]\.\d\.\d{1,2})\b", notes)), key=lambda s: [int(x) for x in s.split(".")])
guide = {}
for f in glob.glob("guide/**/*.md", recursive=True):
    guide[f.replace(BS, "/")] = open(f, encoding="utf-8").read()
qtag = collections.defaultdict(list)
for key in ("m1", "m2", "t"):
    for p in sorted(glob.glob(f"practice/src/{key}-p*.txt")):
        for q in parse(p):
            qtag[q["task"]].append(f"{key}:Q{q['n']}")
rows, gaps = [], []
for s in skill_ids:
    files = sorted(f.split("/")[-1].replace(".md", "") for f, t in guide.items() if re.search(rf"(?<![\d.]){re.escape(s)}(?![\d])", t))
    qs = qtag.get(s, [])
    rows.append((s, files, qs))
    if not files:
        gaps.append(s)
out = ["# Coverage matrix (generated by tools/make_coverage_matrix.py)", "",
       f"Skills parsed from exam guide v1.1 notes: **{len(skill_ids)}**. Guide coverage = files that cite the skill id; practice = questions tagged with the skill id (m1/m2 = mocks, t = topic sets). Skills with no tagged question are covered by flashcards/cheatsheets or are conceptual (listed below).", "",
       "| Skill | Guide sections citing it | Practice questions |", "|---|---|---|"]
for s, files, qs in rows:
    out.append(f"| {s} | {', '.join(files) if files else '—'} | {len(qs)}{(' (' + ', '.join(qs[:4]) + ('…' if len(qs) > 4 else '') + ')') if qs else ''} |")
nq = [s for s, f, q in rows if not q]
out += ["", f"## Summary", f"- Skills with ≥1 guide section: {len(rows) - len(gaps)} / {len(rows)}",
        f"- Skills with ≥1 practice question: {len(rows) - len(nq)} / {len(rows)}",
        f"- Skills with no guide citation: {', '.join(gaps) if gaps else 'none'}",
        f"- Skills with no practice question ({len(nq)}): {', '.join(nq)}", "",
        "## Intentional omissions / light coverage (justification)",
        "- Language-specific syntax, ML training/inference, business conclusions: explicitly out of scope in the exam guide.",
        "- 1.4.11 data structures/algorithms and 1.4.10 distributed computing: conceptual; covered in guide 1.4 §9–§10, no dedicated question (low expected weight).",
        "- Services in scope but only lightly covered: Managed Grafana, AWS Batch, Data Exchange, Kendra, Amazon Q, CloudFront, Route 53, WAF/Shield, EBS/EFS beyond Lambda mounting — listed in guide for recognition only.",
        "- Timestream: not on the v1.1 in-scope list (and removed from the out-of-scope list) — minimal coverage by design."]
open("docs/coverage-matrix.md", "w", encoding="utf-8").write("\n".join(out) + "\n")
print(len(rows), "skills;", len(gaps), "without guide;", len(nq), "without question")
