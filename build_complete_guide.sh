#!/usr/bin/env bash
# Builds DEA-Complete-Guide.md by concatenating the guide in reading order (no content is retyped).
# Optional PDF only if pandoc is already installed. Run from repo root: bash build_complete_guide.sh
set -euo pipefail
cd "$(dirname "$0")"
OUT=DEA-Complete-Guide.md
FILES=(
  README.md
  guide/00-exam-overview.md
  guide/D1-ingestion-transformation/1.1-ingestion.md
  guide/D1-ingestion-transformation/1.2-transform.md
  guide/D1-ingestion-transformation/1.3-orchestration.md
  guide/D1-ingestion-transformation/1.4-programming.md
  guide/D2-data-store-management/2.1-stores.md
  guide/D2-data-store-management/2.2-catalog.md
  guide/D2-data-store-management/2.3-lifecycle.md
  guide/D2-data-store-management/2.4-modeling.md
  guide/D3-operations-support/3.1-automation.md
  guide/D3-operations-support/3.2-analysis.md
  guide/D3-operations-support/3.3-monitoring.md
  guide/D3-operations-support/3.4-data-quality.md
  guide/D4-security-governance/4.1-authentication.md
  guide/D4-security-governance/4.2-authorization-lakeformation.md
  guide/D4-security-governance/4.3-encryption-masking.md
  guide/D4-security-governance/4.4-audit-logs.md
  guide/D4-security-governance/4.5-privacy-governance.md
  guide/X-cross-cutting.md
  cheatsheets/00-which-service-when.md
  cheatsheets/05-limits-and-numbers.md
  cheatsheets/12-commonly-confused-pairs.md
  cheatsheets/11-acronyms.md
  docs/exam-day-playbook.md
)
: > "$OUT"
printf '%s\n\n' "<!-- Generated by build_complete_guide.sh on $(date -u +%Y-%m-%dT%H:%MZ). Do not edit; edit the source files. -->" >> "$OUT"
for f in "${FILES[@]}"; do
  if [ ! -f "$f" ]; then echo "MISSING: $f" >&2; exit 1; fi
  printf '\n\n---\n\n<!-- source: %s -->\n\n' "$f" >> "$OUT"
  cat "$f" >> "$OUT"
done
echo "Built $OUT: $(wc -l < "$OUT") lines from ${#FILES[@]} files"
if command -v pandoc >/dev/null 2>&1; then
  pandoc "$OUT" -o DEA-Complete-Guide.pdf --toc 2>/dev/null && echo "PDF built" || echo "pandoc present but PDF build failed (needs a LaTeX engine); skipped"
else
  echo "pandoc not installed: PDF skipped"
fi
